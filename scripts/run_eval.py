#!/usr/bin/env python3
"""Stage D: the readout eval. For each Stage-C-passing item, at each fitted layer, at the
bank's own read position, applies the J-lens and records target/surface/model-next-token
ranks. Writes one tidy row per (item, layer, position) to parquet -- all aggregation
(Stage F) happens downstream of this file.

Usage:
    python scripts/run_eval.py config/smoke.qwen3.5-0.8b.yaml

Requires scripts/download_artifacts.py, scripts/run_gate.py (check 1 passing), and
scripts/run_behavioral.py to have been run against the same config first.
"""

import argparse
import dataclasses
import logging
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import _bootstrap  # noqa: F401

import pyarrow as pa
import pyarrow.parquet as pq

from typo_readout.bank_io import bank_artifact_record, load_retained_items
from typo_readout.config import REPO_ROOT, Config
from typo_readout.eval_loop import run_eval
from typo_readout.lens_io import load_lens
from typo_readout.model_io import load_model
from typo_readout.provenance import ArtifactRecord, write_provenance


def main() -> None:
    logging.basicConfig(level=logging.WARNING, format="[%(levelname)s] %(message)s")
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("config", help="path to a config/*.yaml file")
    args = parser.parse_args()

    config = Config.load(args.config)
    print(f"[eval] config: {args.config} (tier={config.run.tier})")

    retained_items, n_subset = load_retained_items(config)
    print(
        f"[eval] {len(retained_items)}/{n_subset} items retained from Stage C "
        f"(bank.n_items={config.bank.n_items!r}): {[i['name'] for i in retained_items]}"
    )
    if not retained_items:
        print("[eval] no retained items -- nothing to evaluate. Refusing to write an empty run.")
        sys.exit(1)

    print(f"[eval] loading lens: {config.lens.repo}/{config.lens.filename}")
    lens = load_lens(config.lens)
    print(f"[eval] lens: {lens!r}")

    print(f"[eval] loading model: {config.model.hf_repo} (dtype={config.model.dtype})")
    loaded = load_model(config.model)
    print(f"[eval] model loaded via {loaded.auto_class_used} on device={loaded.device}")

    print(
        f"[eval] running eval: {len(retained_items)} items x "
        f"{len(lens.source_layers) if config.lens.layers is None else len(config.lens.layers)} layers x "
        f"{len(config.bank.read_position_offsets)} position(s) ..."
    )
    rows = run_eval(lens, loaded.lens_model, retained_items, config.bank)
    print(f"[eval] produced {len(rows)} rows")

    n_multi_token = sum(1 for r in rows if not r.target_is_single_token)
    if n_multi_token:
        multi_items = sorted({r.item for r in rows if not r.target_is_single_token})
        print(
            f"[eval] WARNING: {len(multi_items)} item(s) have a CORRECTED word that is NOT "
            f"a single token under {config.model.hf_repo}'s tokenizer (used first diverging "
            f"token as a documented best-effort -- see target_is_single_token column): {multi_items}"
        )
    n_surface_fragmented = sum(1 for r in rows if not r.surface_is_single_token)
    if n_surface_fragmented:
        frag_items = sorted({r.item for r in rows if not r.surface_is_single_token})
        print(
            f"[eval] INFO: {len(frag_items)} item(s) have a misspelled surface word that "
            f"fragments into >1 token past the shared prefix (expected/harmless -- rare "
            f"misspellings usually lack their own BPE token; does not affect target scoring, "
            f"see surface_is_single_token column): {frag_items}"
        )

    run_dir = REPO_ROOT / "runs" / f"eval-{config.run.tier}"
    run_dir.mkdir(parents=True, exist_ok=True)
    parquet_path = run_dir / "eval_rows.parquet"

    table = pa.Table.from_pylist([dataclasses.asdict(r) for r in rows])
    pq.write_table(table, parquet_path)
    print(f"[eval] wrote {parquet_path} ({table.num_rows} rows, {table.num_columns} columns)")

    provenance_path = write_provenance(
        config=config,
        stage="eval",
        artifacts=[
            bank_artifact_record(config.bank),
            ArtifactRecord.from_file(parquet_path, source="generated by scripts/run_eval.py"),
        ],
        extra={
            "eval_n_items_retained": len(retained_items),
            "eval_n_items_subset": n_subset,
            "eval_n_rows": len(rows),
            "eval_n_multi_token_targets": n_multi_token,
            "eval_auto_class_used": loaded.auto_class_used,
            "eval_device": loaded.device,
            "eval_rows_path": str(parquet_path.relative_to(REPO_ROOT)),
        },
    )
    print(f"[eval] wrote {provenance_path} (and repo-root provenance.json)")


if __name__ == "__main__":
    main()
